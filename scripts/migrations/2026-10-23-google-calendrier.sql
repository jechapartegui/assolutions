-- Transaction atomique, relancable. Ne contacte jamais Google et n'envoie aucun mail.
BEGIN;

CREATE TABLE IF NOT EXISTS public.calendrier (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id integer NOT NULL REFERENCES public.project(id) ON DELETE RESTRICT,
    saison_id integer NOT NULL REFERENCES public.saison(id) ON DELETE RESTRICT,
    nom varchar(255) NOT NULL,
    description text,
    timezone varchar(64) NOT NULL DEFAULT 'Europe/Paris',
    notifier_mises_a_jour boolean NOT NULL DEFAULT false,
    actif boolean NOT NULL DEFAULT true,
    google_calendar_id text UNIQUE,
    google_calendar_url text,
    statut_synchro varchar(24) NOT NULL DEFAULT 'LOCAL_ONLY',
    derniere_synchro timestamptz,
    derniere_erreur text,
    date_creation timestamptz NOT NULL DEFAULT now(),
    date_maj timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_calendrier_nom_non_vide CHECK (length(trim(nom)) > 0),
    CONSTRAINT chk_calendrier_statut CHECK (
        statut_synchro IN ('LOCAL_ONLY', 'PENDING', 'SYNCED', 'ERROR', 'DISABLED')
    ),
    CONSTRAINT uq_calendrier_id_saison UNIQUE (id, saison_id)
);

CREATE INDEX IF NOT EXISTS ix_calendrier_projet_saison
    ON public.calendrier (project_id, saison_id);

-- Rattachement OPTIONAL : toutes les anciennes seances gardent calendrier_id = NULL.
ALTER TABLE public.seance
    ADD COLUMN IF NOT EXISTS calendrier_id integer NULL;

-- FK composite : impossible d'affecter une seance a un calendrier d'une AUTRE saison.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_seance_calendrier_meme_saison'
          AND conrelid = 'public.seance'::regclass
    ) THEN
        ALTER TABLE public.seance ADD CONSTRAINT fk_seance_calendrier_meme_saison
            FOREIGN KEY (calendrier_id, saison_id)
            REFERENCES public.calendrier(id, saison_id)
            ON UPDATE RESTRICT ON DELETE RESTRICT;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_seance_calendrier
    ON public.seance(calendrier_id) WHERE calendrier_id IS NOT NULL;

-- L'audience du calendrier est differente de la convocation a la seance.
CREATE TABLE IF NOT EXISTS public.calendrier_groupe (
    calendrier_id integer NOT NULL REFERENCES public.calendrier(id) ON DELETE CASCADE,
    groupe_id integer NOT NULL REFERENCES public.groupes(id) ON DELETE RESTRICT,
    date_creation timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (calendrier_id, groupe_id)
);
CREATE INDEX IF NOT EXISTS ix_calendrier_groupe_groupe
    ON public.calendrier_groupe(groupe_id);

-- Identifiant Google et statut au niveau de chaque evenement.
-- Si une seance est supprimee, garder l'evenement pour pouvoir le supprimer de Google.
CREATE TABLE IF NOT EXISTS public.calendrier_evenement (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendrier_id integer NOT NULL REFERENCES public.calendrier(id) ON DELETE RESTRICT,
    seance_id integer NULL REFERENCES public.seance(seance_id) ON DELETE SET NULL,
    google_event_id text,
    google_etag text,
    contenu_hash varchar(64),
    statut_synchro varchar(24) NOT NULL DEFAULT 'PENDING',
    tentatives integer NOT NULL DEFAULT 0,
    derniere_synchro timestamptz,
    derniere_erreur text,
    date_creation timestamptz NOT NULL DEFAULT now(),
    date_maj timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_calendrier_evenement_seance UNIQUE (calendrier_id, seance_id),
    CONSTRAINT uq_calendrier_evenement_google UNIQUE (calendrier_id, google_event_id),
    CONSTRAINT chk_calendrier_evenement_statut CHECK (
        statut_synchro IN ('PENDING', 'SYNCING', 'SYNCED', 'ERROR', 'DELETE_PENDING', 'DELETED')
    )
);
CREATE INDEX IF NOT EXISTS ix_calendrier_evenement_retry
    ON public.calendrier_evenement(statut_synchro, date_maj)
    WHERE statut_synchro IN ('PENDING', 'ERROR', 'DELETE_PENDING');

-- Piste d'audit ; aucune adresse personnelle n'est obligatoire dans ce journal.
CREATE TABLE IF NOT EXISTS public.calendrier_synchro_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendrier_id integer REFERENCES public.calendrier(id) ON DELETE SET NULL,
    seance_id integer,
    action varchar(32) NOT NULL,
    statut varchar(24) NOT NULL,
    details jsonb,
    erreur text,
    date_creation timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_calendrier_synchro_log_calendrier
    ON public.calendrier_synchro_log(calendrier_id, date_creation DESC);

-- Protection interprojets : saison et calendrier doivent appartenir au meme projet.
CREATE OR REPLACE FUNCTION public.fn_calendrier_check_project()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_projet integer;
BEGIN
    SELECT s.project_id INTO v_projet FROM public.saison s WHERE s.id = NEW.saison_id;
    IF v_projet IS NULL OR v_projet <> NEW.project_id THEN
        RAISE EXCEPTION 'Calendrier : saison % hors projet %', NEW.saison_id, NEW.project_id;
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_calendrier_check_project ON public.calendrier;
CREATE TRIGGER trg_calendrier_check_project
BEFORE INSERT OR UPDATE OF saison_id, project_id ON public.calendrier
FOR EACH ROW EXECUTE FUNCTION public.fn_calendrier_check_project();

-- Un groupe du calendrier doit etre de la meme saison.
CREATE OR REPLACE FUNCTION public.fn_calendrier_groupe_check_saison()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_saison_calendrier integer; v_saison_groupe integer;
BEGIN
    SELECT saison_id INTO v_saison_calendrier FROM public.calendrier WHERE id = NEW.calendrier_id;
    SELECT saison_id INTO v_saison_groupe FROM public.groupes WHERE id = NEW.groupe_id;
    IF v_saison_calendrier IS NULL OR v_saison_groupe IS NULL
       OR v_saison_calendrier <> v_saison_groupe THEN
        RAISE EXCEPTION 'Calendrier/groupe : saisons incompatibles';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_calendrier_groupe_check_saison ON public.calendrier_groupe;
CREATE TRIGGER trg_calendrier_groupe_check_saison
BEFORE INSERT OR UPDATE ON public.calendrier_groupe
FOR EACH ROW EXECUTE FUNCTION public.fn_calendrier_groupe_check_saison();

-- Une suppression/dissociation locale prepare le nettoyage Google sans perdre l'eventId.
CREATE OR REPLACE FUNCTION public.fn_calendrier_seance_change()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        UPDATE public.calendrier_evenement
        SET statut_synchro = 'DELETE_PENDING', date_maj = now()
        WHERE seance_id = OLD.seance_id AND statut_synchro <> 'DELETED';
        RETURN OLD;
    END IF;
    IF OLD.calendrier_id IS DISTINCT FROM NEW.calendrier_id
       AND OLD.calendrier_id IS NOT NULL THEN
        UPDATE public.calendrier_evenement
        SET statut_synchro = 'DELETE_PENDING', date_maj = now()
        WHERE seance_id = OLD.seance_id AND calendrier_id = OLD.calendrier_id
          AND statut_synchro <> 'DELETED';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_calendrier_seance_delete ON public.seance;
CREATE TRIGGER trg_calendrier_seance_delete
BEFORE DELETE ON public.seance
FOR EACH ROW EXECUTE FUNCTION public.fn_calendrier_seance_change();

DROP TRIGGER IF EXISTS trg_calendrier_seance_reassign ON public.seance;
CREATE TRIGGER trg_calendrier_seance_reassign
BEFORE UPDATE OF calendrier_id ON public.seance
FOR EACH ROW EXECUTE FUNCTION public.fn_calendrier_seance_change();

COMMIT;

